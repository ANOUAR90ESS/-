export interface AssetSelection {
  label: string;
  keys: string[];
}

/** يعيد أسماء الأصول التي أنتجت مفاتيح هذه القاعدة، بصياغة المستخدم نفسه. */
const labelsForRule = (rule: ComboRule, selections: AssetSelection[]): string[] => {
  const combo: string[] = [];
  rule.requires.forEach((req) => {
    const source = selections.find(
      (sel) => sel.keys.includes(req) && !combo.includes(sel.label)
    );
    if (source) combo.push(source.label);
  });
  return combo;
};

/**
 * يولّد أفكاراً مخصصة من تركيبة الأصول.
 * يفضّل التركيبات (أصلان فأكثر) على الأصل الواحد، ويكمل العدد عند الحاجة.
 */
export const generateIdeasFromAssets = (
  selections: AssetSelection[],
  limit = 4
): ScannedIdea[] => {
  const owned = new Set(selections.flatMap((sel) => sel.keys));
  const labels = selections.map((sel) => sel.label);

  const matchedCombos = COMBO_RULES.filter((rule) =>
    rule.requires.every((req) => owned.has(req))
  );
  const matchedSingles = SINGLE_ASSET_RULES.filter((rule) =>
    rule.requires.every((req) => owned.has(req))
  );

  const chosen = [...matchedCombos, ...matchedSingles].slice(0, limit);

  return chosen.map((rule) => ({
    id: rule.id,
    assetCombo: labelsForRule(rule, selections),
    ...rule.build(labels)
  }));
};
